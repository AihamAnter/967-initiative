// The interactive directory only needs card/search fields, not full profiles or provenance.
export function toCompanyDirectoryCard(company){
 return Object.fromEntries(['id','name','category','location','scale','summary','products','strengths','imageUrl','imagePosition','isDemo','isVerified'].map(key=>[key,company[key]]));
}

export function mapYemeniCompany(row) {
  const productDetails = Array.isArray(row.products) ? row.products.filter(product => product?.name).map(product => ({
    name: product.name,
    description: product.description || '',
    format: product.format || '',
    imageUrl: product.image_url || product.imageUrl || null,
    size: product.size || '',
    weight: product.weight || '',
    quantity: product.quantity ?? null,
    wholesalePrice: product.wholesale_price ?? product.wholesalePrice ?? null,
    retailPrice: product.retail_price ?? product.retailPrice ?? null,
    currency: product.currency || 'YER',
    sources: normalizeCompanySources(product.sources),
  })) : [];
  return {
    id: row.slug,
    databaseId: row.id,
    name: row.name,
    legalName: row.legal_name,
    category: row.category,
    location: row.location,
    scale: row.scale,
    entityType: row.entity_type,
    ownership: row.ownership,
    owner: row.owner_name,
    ceo: row.ceo_name,
    founded: row.founded,
    teamSize: row.team_size,
    address: row.address,
    googleMapsUrl: row.google_maps_url || null,
    website: row.website,
    email: row.email,
    phone: row.phone,
    summary: row.summary,
    story: row.story,
    impact: row.impact,
    strengths: Array.isArray(row.strengths) ? row.strengths : [],
    markets: Array.isArray(row.markets) ? row.markets : [],
    products: productDetails.map(product => product.name),
    productDetails,
    sources: companySources(row.products),
    imageUrl: row.image_url || null,
    imagePosition: row.image_position || 'center',
    isDemo: Boolean(row.is_demo),
    isVerified: Boolean(row.is_verified) && !row.is_demo,
  };
}
